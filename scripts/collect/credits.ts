import { writeFileSync } from 'node:fs';
import type { Manifest, ManifestAsset } from './manifest';

const esc = (s: string) => s.replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');

function row(a: ManifestAsset): string {
  const author = a.authorUrl ? `[${esc(a.author)}](${a.authorUrl})` : esc(a.author);
  const lic = a.licenseUrl ? `[${a.license}](${a.licenseUrl})` : a.license;
  const mod = a.modified ? ' (modified)' : '';
  return `| ${esc(a.title)}${mod} | ${author} | [${esc(a.source.provider)}](${a.source.pageUrl}) | ${lic} |`;
}

/** Deterministic CREDITS.md content: approved assets only, one table per category. */
export function generateCredits(manifest: Manifest): string {
  const approved = manifest.assets.filter((a) => a.status === 'approved');
  const cats = [...new Set(approved.map((a) => `${a.type}/${a.category}`))].sort();
  const lines = [
    '# Credits',
    '',
    'Generated by `npm run assets:credits` from `public/assets/manifest.json`. Do not edit by hand.',
    '',
  ];
  if (cats.length === 0) lines.push('No approved assets.', '');
  for (const cat of cats) {
    lines.push(`## ${cat}`, '', '| Title | Author | Source | License |', '|---|---|---|---|');
    const items = approved
      .filter((a) => `${a.type}/${a.category}` === cat)
      .sort((a, b) => a.id.localeCompare(b.id));
    for (const a of items) lines.push(row(a));
    lines.push('');
  }
  return lines.join('\n');
}

export function writeCredits(path: string, manifest: Manifest): void {
  writeFileSync(path, generateCredits(manifest));
}
